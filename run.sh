#!/usr/bin/env bash
# StatusNeo Insights: one-command launcher.
#   ./run.sh            build (first time) and start everything
#   ./run.sh stop       stop containers (data is kept)
#   ./run.sh restart    restart containers
#   ./run.sh logs       follow server logs
#   ./run.sh status     show container status
#   ./run.sh build      rebuild the image (after changing UI code)
#   ./run.sh reset      DELETE all data and start fresh
set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")"

ENV_FILE=".env.statusneo"
COMPOSE_FILE="compose.statusneo.yaml"
PROJECT="statusneo-insights"
Y=$'\033[38;5;220m'; D=$'\033[2m'; R=$'\033[31m'; B=$'\033[1m'; N=$'\033[0m'
[ -t 1 ] || { Y=""; D=""; R=""; B=""; N=""; }

say()  { printf '%s\n' "${Y}▸${N} $*"; }
die()  { printf '%s\n' "${R}✖ $*${N}" >&2; exit 1; }

banner() {
  printf '%s\n' "${Y}${B}"
  cat <<'ART'
   ____  _        _             _   _
  / ___|| |_ __ _| |_ _   _ ___| \ | | ___  ___
  \___ \| __/ _` | __| | | / __|  \| |/ _ \/ _ \
   ___) | || (_| | |_| |_| \__ \ |\  |  __/ (_) |
  |____/ \__\__,_|\__|\__,_|___/_| \_|\___|\___/   Insights
ART
  printf '%s\n' "${N}"
}

need_docker() {
  command -v docker >/dev/null 2>&1 || die "Docker is not installed. Get it from https://docs.docker.com/get-docker/"
  docker info >/dev/null 2>&1 || die "Docker is installed but not running. Start Docker and try again."
  if docker compose version >/dev/null 2>&1; then
    DC=(docker compose)
  elif command -v docker-compose >/dev/null 2>&1; then
    DC=(docker-compose)
  else
    die "Docker Compose is missing. Install the Compose plugin: https://docs.docker.com/compose/install/"
  fi
}

rand_hex() {
  if command -v openssl >/dev/null 2>&1; then openssl rand -hex 32
  else head -c 32 /dev/urandom | od -An -tx1 | tr -d ' \n'; fi
}

ensure_env() {
  if [ -f "$ENV_FILE" ]; then return; fi
  say "Creating ${ENV_FILE} with fresh secrets"
  umask 077
  cat > "$ENV_FILE" <<ENVEOF
# Generated by run.sh. Keep this file private and do not commit it.
POSTGRES_PASSWORD=$(rand_hex)
REDASH_COOKIE_SECRET=$(rand_hex)
REDASH_SECRET_KEY=$(rand_hex)
STATUSNEO_PORT=5000
REDASH_HOST=http://localhost:5000
ENVEOF
}

dc() { "${DC[@]}" -p "$PROJECT" --env-file "$ENV_FILE" -f "$COMPOSE_FILE" "$@"; }

port() { grep -E '^STATUSNEO_PORT=' "$ENV_FILE" | cut -d= -f2; }

db_ready() {
  dc exec -T postgres psql -U postgres -tAc \
    "SELECT 1 FROM information_schema.tables WHERE table_name='organizations'" 2>/dev/null | grep -q 1
}

wait_for_app() {
  local url="http://localhost:$(port)/ping" tries=90
  say "Waiting for the app at ${url}"
  while [ $tries -gt 0 ]; do
    if command -v curl >/dev/null 2>&1; then
      curl -fsS "$url" >/dev/null 2>&1 && return 0
    else
      dc exec -T server python -c "import urllib.request;urllib.request.urlopen('http://localhost:5000/ping')" >/dev/null 2>&1 && return 0
    fi
    tries=$((tries-1)); sleep 2
  done
  return 1
}

cmd_up() {
  banner
  need_docker
  ensure_env
  say "Building the image (first build takes several minutes: it compiles the UI)"
  dc build
  say "Starting database and cache"
  dc up -d postgres redis
  say "Waiting for the database"
  local n=60
  until dc exec -T postgres pg_isready -U postgres >/dev/null 2>&1; do
    n=$((n-1)); [ $n -gt 0 ] || die "Postgres did not start. Check: ./run.sh logs"
    sleep 2
  done
  if ! db_ready; then
    say "Creating database tables (first run)"
    dc run --rm server create_db
  fi
  say "Starting StatusNeo Insights"
  dc up -d
  if wait_for_app; then
    printf '\n%s\n' "${Y}${B}  Ready:${N} http://localhost:$(port)"
    printf '%s\n' "${D}  Open it, press Launch Insights, and the first sign-in walks you through setup.${N}"
    printf '%s\n\n' "${D}  Stop with ./run.sh stop   |   Logs with ./run.sh logs${N}"
  else
    die "The app did not become healthy in time. Check: ./run.sh logs"
  fi
}

cmd="${1:-up}"
case "$cmd" in
  up|start)  cmd_up ;;
  stop|down) need_docker; ensure_env; dc down ;;
  restart)   need_docker; ensure_env; dc restart ;;
  logs)      need_docker; ensure_env; dc logs -f --tail=100 server worker scheduler ;;
  status|ps) need_docker; ensure_env; dc ps ;;
  build)     need_docker; ensure_env; dc build ;;
  reset)
    need_docker; ensure_env
    printf '%s' "${R}This deletes ALL StatusNeo Insights data (queries, dashboards, users). Type 'delete' to continue: ${N}"
    read -r answer
    [ "$answer" = "delete" ] || die "Cancelled."
    dc down -v
    say "Data removed. Run ./run.sh to start fresh."
    ;;
  help|-h|--help) sed -n '2,10p' "$0" ;;
  *) die "Unknown command '$cmd'. Try: ./run.sh help" ;;
esac
